"""Generate image prompts, alt-text scaffold, caption skeleton and checklist from frozen slides.md.
Usage: python3 build_package.py post_folder --stencil "a stomach with the C-shaped duodenal loop" [--topic "Peptic ulcer disease"]
Writes into post_folder: image-prompts.md, alt-text.txt, caption.txt (skeleton), checklist.md
The Visual and Packaging worker then polishes: layout lines, alt-text descriptions, caption hook and hashtags.
"""
import argparse, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from slideslib import parse, AUS_WATCH

ap = argparse.ArgumentParser()
ap.add_argument("post")
ap.add_argument("--stencil", required=True)
ap.add_argument("--topic", default="")
a = ap.parse_args()

here = os.path.dirname(os.path.abspath(__file__))
style = open(os.path.join(here, "..", "brand", "style-block.md"), encoding="utf-8").read().strip()
style = style.replace("{STENCIL}", a.stencil)
slides = parse(os.path.join(a.post, "slides.md"))
NO_EXTRA = ("Do not add any other text: no footer, disclaimer, slide numbers, labels, logos, "
            "watermarks, handles or gibberish lettering. Icons and the stencil contain no letters or numbers.")

def warnings(text):
    found = [w for w in AUS_WATCH if w.lower() in text.lower()]
    if not found:
        return ""
    return ("Australian spelling is intentional, render exactly: " +
            ", ".join(f'"{w}"' for w in found) + ". Do not change to US spelling.")

out = [f"# Image prompts: {a.topic or os.path.basename(a.post)}\n",
       "Generated by build_package.py from the frozen slides.md. Run slide 1 first in a fresh ChatGPT chat; "
       "run slides 2 onwards in the same chat. Save as slide-01.png etc., then upload for Image QA.\n"]
qa = ["\n## Image QA checklist (exact strings)\n"]
for s in slides:
    exact = f'Headline: "{s["headline"]}"\nBody: "{s["body"]}"'
    lead = style if s["n"] == 1 else ("Match the exact style of the first image (slide 1): same background, stencil, "
                                      "glass cards, fonts, colours and icon weight.\n\n" + style)
    layout = f"Layout and icon for this slide: {s['visual']}" if s["visual"] else "Layout: headline at top, body in one glass card."
    prompt = "\n\n".join(p for p in [lead, layout,
              "EXACT TEXT. Render exactly as written, character for character, no changes:\n" + exact,
              warnings(s["headline"] + " " + s["body"]), NO_EXTRA] if p)
    out.append(f"\n## Slide {s['n']}: {s['title']}\n\n```\n{prompt}\n```\n")
    qa.append(f"- Slide {s['n']}: \"{s['headline']}\" | \"{s['body']}\"")
open(os.path.join(a.post, "image-prompts.md"), "w", encoding="utf-8").write("".join(out) + "\n".join(qa) + "\n")

alt = [f"Slide {s['n']}: {s['headline']}. {s['body']} [DESCRIBE VISUAL: {s['visual']}]" for s in slides]
open(os.path.join(a.post, "alt-text.txt"), "w", encoding="utf-8").write("\n\n".join(alt) + "\n")

hook = slides[0]["headline"] if slides else ""
caption = f"""{hook}

[2 to 4 lines: the key takeaway in our own words]

Save this for later and share with a colleague.

Educational content only, not medical advice.
References: [open sources from slides.md key claims]

[3 to 5 hashtags]
"""
open(os.path.join(a.post, "caption.txt"), "w", encoding="utf-8").write(caption)

checklist = """# Posting checklist
- [ ] GM A accuracy: PASS
- [ ] Compliance: PASS
- [ ] Text check script: PASS
- [ ] Sync check script: PASS
- [ ] Caption polished (hook, takeaway, references, hashtags)
- [ ] Images generated and saved (slide-01.png onwards)
- [ ] Image QA: PASS on every slide
- [ ] Owner checks done (see run report)
- [ ] Scheduled: [date], 5:30pm AWST, cross-post to Pinterest
"""
open(os.path.join(a.post, "checklist.md"), "w", encoding="utf-8").write(checklist)
print(f"Built package for {len(slides)} slides in {a.post}")
